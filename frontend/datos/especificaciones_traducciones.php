// nombre del dato (la fila de la tabla) en el idioma actual
function nombreDatoFicha($campo)
{
    $claves = [
        "Motor"            => "ficha.motor",
        "Cilindrada"       => "ficha.cilindrada",
        "Potencia"         => "ficha.potencia",
        "Torque"           => "ficha.torque",
        "Aceleración"      => "ficha.aceleracion",
        "Velocidad máxima" => "ficha.velocidad",
        "Tracción"         => "ficha.traccion",
        "Peso"             => "ficha.peso",
    ];
    return isset($claves[$campo]) ? t($claves[$campo]) : $campo;
}

// valor del dato en el idioma actual. Si no hay traducción
// (o el texto original cambió), se devuelve el valor tal cual
function datoFichaTraducido($id, $campo, $valor)
{
    global $traduccionesFicha;

    if ($valor === "No disponible") {
        return t("ficha.no_disponible");
    }

    $idioma = idiomaActual();
    $id = (int) $id;
    if ($idioma === "es" || !isset($traduccionesFicha[$id][$campo][$idioma])) {
        return $valor;
    }
    if ($traduccionesFicha[$id][$campo]["es"] !== $valor) {
        return $valor;
    }
    return $traduccionesFicha[$id][$campo][$idioma];
}
